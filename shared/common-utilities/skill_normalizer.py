def normalize_skill(skill_name: str) -> str:
    """Normalize skill name to canonical form."""
    if not skill_name:
        return ""
    key = skill_name.strip().lower()
    return CANONICAL_SKILL_MAP.get(key, skill_name.strip())

def get_skill_category(skill_name: str) -> str:
    """Return category for a given skill name."""
    can = normalize_skill(skill_name)
    return CANONICAL_CATEGORY_MAP.get(can, "Domain-Specific Skills")

def deduplicate_skills(skills: List[str]) -> List[str]:
    """Deduplicate and normalize a list of skill names preserving order."""
    seen: Set[str] = set()
    result: List[str] = []
    for s in skills:
        norm = normalize_skill(s)
        k = norm.lower()
        if k and k not in seen:
            seen.add(k)
            result.append(norm)
    return result
