export function normalizeSkill(rawSkill) {
  if (!rawSkill || typeof rawSkill !== 'string') return '';
  const cleaned = rawSkill.trim().toLowerCase();
  return SKILL_NORMALIZATION_MAP[cleaned] || rawSkill.trim();
}

export function categorizeSkill(skillName) {
  const canonical = normalizeSkill(skillName);
  return SKILL_CATEGORY_MAP[canonical] || 'Domain-Specific Skills';
}

export function deduplicateSkills(skillsInput) {
  const list = Array.isArray(skillsInput)
    ? skillsInput
    : typeof skillsInput === 'string'
    ? skillsInput.split(',').map((s) => s.trim()).filter(Boolean)
    : [];

  const seen = new Set();
  const result = [];

  for (const item of list) {
    const canonical = normalizeSkill(item);
    const key = canonical.toLowerCase();
    if (!seen.has(key) && key.length > 0) {
      seen.add(key);
      result.push(canonical);
    }
  }

  return result;
}
