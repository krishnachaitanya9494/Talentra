class ResumeExtractionService:
    def parse_resume_text(self, filename: str, text: str) -> ExtractedCandidateRecordSchema:
        """Deterministically extract structured fields with provenance."""
        provenance: Dict[str, ProvenanceField] = {}

        # 1. Email extraction
        email_match = EMAIL_REGEX.search(text)
        email = email_match.group(0) if email_match else ""
        if email:
            provenance["email"] = ProvenanceField(value=email, confidence=1.0, source_snippet=email_match.group(0))

        # 2. Phone extraction
        phone_match = PHONE_REGEX.search(text)
        phone = phone_match.group(0) if phone_match else ""
        if phone:
            provenance["phone"] = ProvenanceField(value=phone, confidence=1.0, source_snippet=phone_match.group(0))

        # 3. Experience extraction
        exp_match = EXP_REGEX.search(text)
        total_exp = float(exp_match.group(1)) if exp_match else None
        if total_exp is not None:
            provenance["total_experience_years"] = ProvenanceField(
                value=str(total_exp), confidence=0.95, source_snippet=exp_match.group(0)
            )

        # 4. Name extraction (first line or before email)
        lines = [line.strip() for line in text.split('\n') if line.strip()]
        name = ""
        for line in lines[:5]:
            if "@" not in line and not any(char.isdigit() for char in line) and len(line) < 40:
                name = line
                provenance["name"] = ProvenanceField(value=name, confidence=0.9, source_snippet=line)
                break
        if not name and filename:
            clean_fn = re.sub(r'(_resume|\.pdf|\.docx|\.txt)', '', filename, flags=re.I).replace('_', ' ')
            name = clean_fn.title()

        # 5. Skills extraction
        found_skills = []
        for sk in KNOWN_SKILLS:
            if re.search(r'\b' + re.escape(sk) + r'\b', text, re.IGNORECASE):
                found_skills.append(sk)
        if found_skills:
            provenance["skills"] = ProvenanceField(
                value=", ".join(found_skills), confidence=1.0, source_snippet="Extracted via exact dictionary match"
            )

        # Notice period & compensation: extract ONLY if explicitly written
        notice_match = re.search(r'(\d+[\s-]*(?:days?|months?)\s*notice\s*period)', text, re.IGNORECASE)
        notice = notice_match.group(1) if notice_match else ""

        comp_match = re.search(r'(?:ctc|compensation|salary)[\s:]*([0-9.,]+\s*(?:lpa|inr|\$|k)?)', text, re.IGNORECASE)
        compensation = comp_match.group(1) if comp_match else ""

        return ExtractedCandidateRecordSchema(
            id=re.sub(r'[^a-zA-Z0-9]', '', filename),
            filename=filename,
            name=name,
            email=email,
            phone=phone,
            current_role=lines[1] if len(lines) > 1 and len(lines[1]) < 60 else "",
            total_experience_years=total_exp,
            skills=found_skills,
            notice_period=notice,
            compensation=compensation,
            provenance=provenance,
        )
